const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
test('首次引导只持久化完成标记；演示副本可分析；重定位后刷新数据且坏路径不破坏登记', async t => {
  const { createServer } = require('../src/serverApp');
  const { resolveRuntimePaths } = require('../src/runtimePaths');
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'antenna-onboarding-'));
  const demoDir = require('../../desktop/tests/fixtures.cjs').createDemo(path.join(root, 'fixtures')).sourceDir;
  const paths = { ...resolveRuntimePaths({ channel: 'dev', sourceRoot: path.resolve(__dirname, '../..'), dataDir: path.join(root, 'data') }), demoDir };
  let server = createServer({ paths }); let origin = (await server.listen()).origin;
  t.after(async () => { await server.close(); fs.rmSync(root, { recursive: true, force: true }); });
  const call = async (url, method = 'GET', body) => { const response = await fetch(origin + '/api' + url, { method, headers: { 'Content-Type': 'application/json' }, body: body === undefined ? undefined : JSON.stringify(body) }); return { status: response.status, data: await response.json() }; };
  assert.deepEqual((await call('/onboarding')).data.completed, false);
  assert.equal((await call('/onboarding/demo', 'POST')).status, 200);
  const sources = (await call('/sources')).data; assert.equal(sources.length, 1); assert.equal(sources[0].tasks.length, 3);
  assert.ok(sources[0].path.startsWith(paths.dataDir)); assert.notEqual(sources[0].path, demoDir);
  const relocated = path.join(root, '移动后的演示'); fs.renameSync(sources[0].path, relocated);
  const bad = await call(`/sources/${sources[0].id}/relocate`, 'POST', { path: path.join(root, 'missing') }); assert.equal(bad.status, 400);
  assert.equal(server.sourcesStore.get(sources[0].id).path, sources[0].path);
  const updated = await call(`/sources/${sources[0].id}/relocate`, 'POST', { path: relocated }); assert.equal(updated.status, 200);
  const after = (await call('/sources')).data; assert.equal(after.length, 1); assert.equal(after[0].path, relocated); assert.equal(after[0].offline, false);
  assert.equal((await call('/onboarding/complete', 'POST')).data.completed, true);
  await server.close(); server = createServer({ paths }); origin = (await server.listen()).origin;
  assert.equal((await call('/onboarding')).data.completed, true);
});
